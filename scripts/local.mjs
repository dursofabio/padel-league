/**
 * Local development in one command (Mac, Windows, Linux): `npm run local`.
 *
 * 1. checks that Docker is running
 * 2. starts Supabase in Docker (database, auth, realtime, mail catcher) with the migrations
 * 3. writes .env.local with the local URL and publishable key (read by Vite)
 * 4. loads the demo data the first time (or always with --demo)
 * 5. starts the app on http://localhost:5173
 *
 *   npm run local                start (demo data only if the database is empty)
 *   npm run local -- --demo      start and reload the demo tournament from scratch
 *   npm run local:stop           stop the containers (data are kept)
 *   npm run local:reset          wipe the local database and re-apply migrations + courts
 */
import { spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const win = process.platform === 'win32';
const bin = (name) => path.join(root, 'node_modules', '.bin', win ? `${name}.cmd` : name);
const args = process.argv.slice(2);
const step = (s) => console.log(`\n\x1b[1m▸ ${s}\x1b[0m`);
const fail = (s) => {
  console.error(`\n\x1b[31m✖ ${s}\x1b[0m`);
  process.exit(1);
};

// services the app does not use: fewer images to download, faster start
const EXCLUDE = 'studio,imgproxy,storage-api,edge-runtime,logflare,vector,supavisor,postgres-meta';

const run = (cmd, a, opts = {}) => spawnSync(cmd, a, { cwd: root, stdio: 'inherit', shell: win, ...opts });

if (!fs.existsSync(bin('supabase')) || !fs.existsSync(bin('vite'))) fail('Missing dependencies: run "npm install" first.');

if (args.includes('--stop')) {
  step('Stopping local Supabase');
  process.exit(run(bin('supabase'), ['stop']).status ?? 0);
}
if (args.includes('--reset')) {
  step('Resetting the local database (migrations and courts re-applied)');
  process.exit(run(bin('supabase'), ['db', 'reset']).status ?? 0);
}

step('Checking Docker');
if (spawnSync('docker', ['info'], { stdio: 'ignore', shell: win }).status !== 0)
  fail('Docker is not responding. Start Docker Desktop, wait until it is ready and try again.');

step('Starting Supabase in Docker (the first time it downloads the images: a few minutes)');
// after a Docker restart the old containers may still be booting ("not ready"): wait and retry,
// then restart them (the database volume is kept)
const start = () => run(bin('supabase'), ['start', '-x', EXCLUDE]).status === 0;
let started = start();
for (let i = 1; !started && i <= 2; i++) {
  console.log(`Supabase is not ready yet: retrying in 15 seconds (${i}/2)…`);
  await new Promise((r) => setTimeout(r, 15000));
  started = start();
}
if (!started) {
  console.log('Restarting the Supabase containers (data are kept)…');
  run(bin('supabase'), ['stop']);
  started = start();
}
if (!started) fail('Supabase did not start: see the message above.');

const status = spawnSync(bin('supabase'), ['status', '-o', 'json'], { cwd: root, encoding: 'utf8', shell: win });
let s;
try {
  s = JSON.parse(status.stdout.slice(status.stdout.indexOf('{')));
} catch {
  fail('Cannot read the Supabase status (supabase status).');
}
const url = s.API_URL;
const publishable = s.PUBLISHABLE_KEY || s.ANON_KEY;
const secret = s.SECRET_KEY || s.SERVICE_ROLE_KEY;
if (!url || !publishable || !secret) fail('Local Supabase keys not found.');

step('Writing .env.local for the app');
fs.writeFileSync(
  path.join(root, '.env.local'),
  `# Generated by npm run local: local Supabase in Docker\nVITE_SUPABASE_URL=${url}\nVITE_SUPABASE_PUBLISHABLE_KEY=${publishable}\n`,
);

const isEmpty = async () => {
  const r = await fetch(`${url}/rest/v1/tournaments?select=id&limit=1`, { headers: { apikey: secret, Authorization: `Bearer ${secret}` } });
  return r.ok && (await r.json()).length === 0;
};
if (args.includes('--demo') || (await isEmpty())) {
  step('Loading the demo data (20 pairs, password "password")');
  const seed = run(process.execPath, [path.join(root, 'scripts', 'seed-demo.mjs')], {
    shell: false,
    env: { ...process.env, SUPABASE_URL: url, SUPABASE_SECRET_KEY: secret },
  });
  if (seed.status !== 0) fail('Loading the demo data failed.');
} else {
  console.log('Data already present: keeping it. To reload the demo tournament: npm run local -- --demo');
}

console.log(`
\x1b[32m✔ Ready\x1b[0m
  App:              http://localhost:5173
  Emails (fake):    ${s.MAILPIT_URL || s.INBUCKET_URL || 'http://127.0.0.1:54324'}
  Demo users:       admin@demo.it, org@demo.it, gestore@demo.it, p1@demo.it … p40@demo.it
  Password:         password
  From a phone:     http://<computer-IP-address>:5173 (same Wi‑Fi network)

  Ctrl+C stops the app; the containers keep running (npm run local:stop to stop them).
`);

step('Starting the app');
const vite = spawn(bin('vite'), ['--host'], { cwd: root, stdio: 'inherit', shell: win });
vite.on('exit', (code) => process.exit(code ?? 0));
