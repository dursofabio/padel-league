/**
 * Local development in one command (Mac, Windows, Linux): `npm run locale`.
 *
 * 1. checks that Docker is running
 * 2. starts Supabase in Docker (database, auth, realtime, mail catcher) with the migrations
 * 3. writes .env.local with the local URL and publishable key (read by Vite)
 * 4. loads the demo data the first time (or always with --demo)
 * 5. starts the app on http://localhost:5173
 *
 *   npm run locale               start (demo data only if the database is empty)
 *   npm run locale -- --demo     start and reload the demo tournament from scratch
 *   npm run locale:stop          stop the containers (data are kept)
 *   npm run locale:reset         wipe the local database and re-apply migrations + courts
 */
import { spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const win = process.platform === 'win32';
const bin = (name) => path.join(root, 'node_modules', '.bin', win ? `${name}.cmd` : name);
const args = process.argv.slice(2);
const step = (s) => console.log(`\n\x1b[1m▸ ${s}\x1b[0m`);
const fail = (s) => {
  console.error(`\n\x1b[31m✖ ${s}\x1b[0m`);
  process.exit(1);
};

// services the app does not use: fewer images to download, faster start
const EXCLUDE = 'studio,imgproxy,storage-api,edge-runtime,logflare,vector,supavisor,postgres-meta';

const run = (cmd, a, opts = {}) => spawnSync(cmd, a, { cwd: root, stdio: 'inherit', shell: win, ...opts });

if (!fs.existsSync(bin('supabase')) || !fs.existsSync(bin('vite'))) fail('Dipendenze mancanti: esegui prima "npm install".');

if (args.includes('--stop')) {
  step('Arresto Supabase locale');
  process.exit(run(bin('supabase'), ['stop']).status ?? 0);
}
if (args.includes('--reset')) {
  step('Azzero il database locale (migrazioni e campi riapplicati)');
  process.exit(run(bin('supabase'), ['db', 'reset']).status ?? 0);
}

step('Controllo Docker');
if (spawnSync('docker', ['info'], { stdio: 'ignore', shell: win }).status !== 0)
  fail('Docker non risponde. Avvia Docker Desktop, aspetta che sia pronto e riprova.');

step('Avvio Supabase in Docker (la prima volta scarica le immagini: qualche minuto)');
// after a Docker restart the old containers may still be booting ("not ready"): wait and retry,
// then restart them (the database volume is kept)
const avvia = () => run(bin('supabase'), ['start', '-x', EXCLUDE]).status === 0;
let partito = avvia();
for (let i = 1; !partito && i <= 2; i++) {
  console.log(`Supabase non è ancora pronto: riprovo tra 15 secondi (${i}/2)…`);
  await new Promise((r) => setTimeout(r, 15000));
  partito = avvia();
}
if (!partito) {
  console.log('Riavvio i container di Supabase (i dati restano)…');
  run(bin('supabase'), ['stop']);
  partito = avvia();
}
if (!partito) fail('Supabase non è partito: leggi il messaggio qui sopra.');

const status = spawnSync(bin('supabase'), ['status', '-o', 'json'], { cwd: root, encoding: 'utf8', shell: win });
let s;
try {
  s = JSON.parse(status.stdout.slice(status.stdout.indexOf('{')));
} catch {
  fail('Non riesco a leggere lo stato di Supabase (supabase status).');
}
const url = s.API_URL;
const publishable = s.PUBLISHABLE_KEY || s.ANON_KEY;
const secret = s.SECRET_KEY || s.SERVICE_ROLE_KEY;
if (!url || !publishable || !secret) fail('Chiavi di Supabase locale non trovate.');

step('Scrivo .env.local per l’app');
fs.writeFileSync(
  path.join(root, '.env.local'),
  `# Generated by npm run locale: local Supabase in Docker\nVITE_SUPABASE_URL=${url}\nVITE_SUPABASE_PUBLISHABLE_KEY=${publishable}\n`,
);

const vuoto = async () => {
  const r = await fetch(`${url}/rest/v1/tornei?select=id&limit=1`, { headers: { apikey: secret, Authorization: `Bearer ${secret}` } });
  return r.ok && (await r.json()).length === 0;
};
if (args.includes('--demo') || (await vuoto())) {
  step('Carico i dati demo (20 coppie, password "password")');
  const seed = run(process.execPath, [path.join(root, 'scripts', 'seed-demo.mjs')], {
    shell: false,
    env: { ...process.env, SUPABASE_URL: url, SUPABASE_SECRET_KEY: secret },
  });
  if (seed.status !== 0) fail('Caricamento dei dati demo non riuscito.');
} else {
  console.log('Dati già presenti: li tengo. Per ricaricare il torneo demo: npm run locale -- --demo');
}

console.log(`
\x1b[32m✔ Pronto\x1b[0m
  App:              http://localhost:5173
  Email (finte):    ${s.MAILPIT_URL || s.INBUCKET_URL || 'http://127.0.0.1:54324'}
  Utenti demo:      admin@demo.it, org@demo.it, gestore@demo.it, p1@demo.it … p40@demo.it
  Password:         password
  Da telefono:      http://<indirizzo-IP-del-computer>:5173 (stessa rete Wi‑Fi)

  Ctrl+C ferma l’app; i container restano attivi (npm run locale:stop per fermarli).
`);

step('Avvio l’app');
const vite = spawn(bin('vite'), ['--host'], { cwd: root, stdio: 'inherit', shell: win });
vite.on('exit', (code) => process.exit(code ?? 0));
